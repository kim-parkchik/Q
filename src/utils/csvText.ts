/**
 * 人が表計算ソフト（Excel など）で開く CSV の欄の書き方（見直しの P5）
 *
 * ・字の頭が =・+・-・@（全角の＝・＋・－・＠も）・タブ・改行（CR）だと、Excel などが式として読み、入れた字とちがうもの
 *   （計算した結果や「#NAME?」）を出したり、式を動かしたりする（CSV インジェクション）。そのときだけ、頭に ' を付けて、
 *   字として読ませる（shared/timeqard の guardSpreadsheetText）。Excel では、頭に ' が付いたまま見える。
 *   数字だけの欄（マイナスの額など）はそのまま（数として読まれ、式にはならない）。
 * ・「,」「"」・改行がある値は "" で囲む（中の「"」は「""」にする）。頭が「"」の値（「"=1+1"」など）も囲むので、Excel などは
 *   「"=1+1"」という字として読み、「"」の内側を式にしない。
 * ・使うのは、人が見る一覧表の CSV（勤怠の詳細・労働者名簿・賃金台帳・出勤簿・年次有給休暇管理簿・支給控除一覧表・
 *   月ごとの推移表・年末調整一覧表・保険料の集計表）。届書の電子申請用ファイル・eLTAX・e-Tax のファイル・仕訳データ・
 *   打刻ログは、ほかのソフトや Q が読む決まった形なので、使わない（入れたとおりに書く）。
 * ・' を付けるのは CSV に書くときだけで、会社ファイルの中のデータ・画面・印刷は、入れたとおりのまま。
 */
import { guardSpreadsheetText } from "../../shared/timeqard";

/** CSV の1つの欄（字の頭が = などなら ' を付け、「,」「"」・改行がある値は "" で囲む。null・undefined は空） */
export const csvField = (value: unknown): string => {
  const s = guardSpreadsheetText(value === null || value === undefined ? "" : String(value));
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
